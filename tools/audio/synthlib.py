"""Tiny numpy/scipy synthesis toolkit for the Grace Run sound set (1930s cartoon spirit).

Everything is deterministic (seeded) so the WAV files can be regenerated byte for byte.
Set `synthlib.SR` before synthesising at another sample rate (music uses 22050).
"""
import wave

import numpy as np
from scipy import signal

SR = 44100


def rng(seed):
    return np.random.default_rng(seed)


def n_(dur):
    return max(1, int(round(dur * SR)))


def silence(dur):
    return np.zeros(n_(dur))


# ---------------------------------------------------------------- oscillators
def osc(freq, n=None, kind="sine", duty=0.5, phase0=0.0):
    """Oscillator. freq is a scalar or a per-sample array (Hz)."""
    if n is None:
        n = len(freq)
    f = np.broadcast_to(np.asarray(freq, dtype=float), (n,))
    ph = phase0 + np.cumsum(f) / SR
    if kind == "sine":
        return np.sin(2 * np.pi * ph)
    p = ph % 1.0
    if kind == "saw":
        return 2 * p - 1
    if kind == "square":
        return np.where(p < duty, 1.0, -1.0)
    if kind == "tri":
        return 2 * np.abs(2 * p - 1) - 1
    raise ValueError(kind)


def glide(f0, f1, n, power=1.0):
    """Exponential pitch glide f0 -> f1 over n samples."""
    x = np.linspace(0.0, 1.0, n) ** power
    return f0 * (f1 / f0) ** x


def vibrato(freq, n, rate=6.0, depth=0.01, delay=0.0, ramp=0.2):
    t = np.arange(n) / SR
    amt = np.clip((t - delay) / max(ramp, 1e-3), 0, 1) * depth
    return np.asarray(freq, dtype=float) * (1 + amt * np.sin(2 * np.pi * rate * t))


def harmonics(f, n, amps, decay_per_h=0.0, tau=None, inharm=0.0):
    """Additive tone: amps[k] is the level of harmonic k+1. Higher partials may decay faster."""
    t = np.arange(n) / SR
    out = np.zeros(n)
    f = np.broadcast_to(np.asarray(f, dtype=float), (n,))
    base = np.cumsum(f) / SR
    for k, a in enumerate(amps):
        h = k + 1
        if a == 0:
            continue
        stretch = np.sqrt(1 + inharm * h * h)
        ph = base * h * stretch
        if f.max() * h * stretch > SR * 0.46:
            continue
        env = 1.0
        if tau is not None:
            env = np.exp(-t / (tau / (1 + decay_per_h * (h - 1))))
        out += a * env * np.sin(2 * np.pi * ph)
    return out


# ---------------------------------------------------------------- envelopes
def expdec(n, tau):
    return np.exp(-np.arange(n) / (tau * SR))


def ar(n, a, tau):
    """Linear attack a seconds then exponential decay."""
    env = expdec(n, tau)
    na = min(n, max(1, int(a * SR)))
    env[:na] *= np.linspace(0, 1, na)
    return env


def adsr(n, a, d, s, r):
    na, nd, nr = int(a * SR), int(d * SR), int(r * SR)
    ns = max(0, n - na - nd - nr)
    parts = [np.linspace(0, 1, max(na, 1), endpoint=False),
             np.linspace(1, s, max(nd, 1), endpoint=False),
             np.full(ns, s),
             np.linspace(s, 0, max(nr, 1))]
    env = np.concatenate(parts)
    if len(env) < n:
        env = np.pad(env, (0, n - len(env)))
    return env[:n]


def bell_env(n, power=2.0):
    x = np.linspace(0, 1, n)
    return np.sin(np.pi * x) ** power


# ---------------------------------------------------------------- noise / filters
def noise(n, seed=0):
    return rng(seed).standard_normal(n)


def _sos(kind, fc, order, fs=None):
    fs = fs or SR
    fc = np.clip(fc, 20, fs * 0.47)
    return signal.butter(order, fc, btype=kind, fs=fs, output="sos")


def lp(x, fc, order=2):
    return signal.sosfilt(_sos("low", fc, order), x)


def hp(x, fc, order=2):
    return signal.sosfilt(_sos("high", fc, order), x)


def bp(x, lo, hi, order=2):
    lo, hi = max(lo, 20), min(hi, SR * 0.47)
    return signal.sosfilt(signal.butter(order, [lo, hi], btype="band", fs=SR, output="sos"), x)


def svf(x, fc, q=2.0, mode="bp"):
    """Time-varying state-variable filter (Chamberlin). fc scalar or per-sample array."""
    n = len(x)
    f = 2 * np.sin(np.pi * np.minimum(np.broadcast_to(np.asarray(fc, dtype=float), (n,)), SR * 0.22) / SR)
    f = f.tolist()
    xs = x.tolist()
    damp = 1.0 / q
    low = band = 0.0
    out = [0.0] * n
    for i in range(n):
        low += f[i] * band
        high = xs[i] - low - damp * band
        band += f[i] * high
        out[i] = band if mode == "bp" else (low if mode == "lp" else high)
    return np.array(out)


def room(x, rt=0.35, mix=0.2, damp=5000, seed=7, extend=True):
    """Cheap room: convolve with a decaying noise impulse response."""
    m = n_(rt * 1.2)
    t = np.arange(m) / SR
    ir = rng(seed).standard_normal(m) * np.exp(-6.9 * t / rt)
    ir = lp(ir, damp, 1)
    ir /= np.sqrt(np.sum(ir ** 2)) + 1e-9
    wet = signal.fftconvolve(x, ir)
    if not extend:
        wet = wet[:len(x)]
        return x + mix * wet
    out = np.zeros(len(wet))
    out[:len(x)] += x
    return out + mix * wet


def echo(x, delay, fb=0.4, taps=4):
    out = np.zeros(len(x) + int(delay * SR * taps) + 1)
    out[:len(x)] += x
    for k in range(1, taps + 1):
        s = int(delay * SR * k)
        out[s:s + len(x)] += x * fb ** k
    return out


def softclip(x, drive=1.5):
    return np.tanh(x * drive) / np.tanh(drive)


# ---------------------------------------------------------------- mixing
class Canvas:
    def __init__(self, dur):
        self.buf = np.zeros(n_(dur))

    def add(self, x, at=0.0, gain=1.0):
        s = int(at * SR)
        if s < 0:
            x = x[-s:]
            s = 0
        if s >= len(self.buf):
            return self
        e = min(len(self.buf), s + len(x))
        self.buf[s:e] += x[:e - s] * gain
        return self

    def trimmed(self, thresh=0.003):
        idx = np.nonzero(np.abs(self.buf) > thresh)[0]
        return self.buf[:idx[-1] + 1] if len(idx) else self.buf


def declick(x, fade_in=0.002, fade_out=0.008):
    x = x.copy()
    a, b = min(len(x), int(fade_in * SR)), min(len(x), int(fade_out * SR))
    if a > 1:
        x[:a] *= np.linspace(0, 1, a)
    if b > 1:
        x[-b:] *= np.linspace(1, 0, b)
    return x


def finish(x, peak=0.8, fade_out=0.01, drive=1.2):
    """Soft-limit, normalise to the given peak (linear) and fade the edges."""
    peak = min(peak, 0.89)
    x = softclip(np.asarray(x, dtype=float), drive) if drive else np.asarray(x, dtype=float)
    m = np.max(np.abs(x)) + 1e-9
    return declick(x / m * peak, 0.0015, fade_out)


def write_wav(path, x, sr=None):
    sr = sr or SR
    data = (np.clip(x, -1.0, 1.0) * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(data.tobytes())


def read_wav(path):
    with wave.open(path, "rb") as w:
        sr, ch, n = w.getframerate(), w.getnchannels(), w.getnframes()
        raw = np.frombuffer(w.readframes(n), dtype="<i2").astype(float) / 32768.0
    if ch > 1:
        raw = raw.reshape(-1, ch).mean(axis=1)
    return sr, raw


def midi_hz(m):
    return 440.0 * 2 ** ((np.asarray(m, dtype=float) - 69) / 12)
